#!/usr/bin/env python3
"""Materialize firebase/shared/*.swift into every widget's Sources/ directory.

The Work42 installer copies each widget's Sources folder on its own, so an installed widget can't reach
../../shared. The canonical files live in shared/; each widget gets a committed copy with a generated header.

  sync-widget-sources.py          write the copies
  sync-widget-sources.py --check  exit 1 if any copy is missing, stale or unexpected (writes nothing)
"""
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
shared = root / "shared"
widgets = sorted((root / "widgets").glob("firebase-*"))
HEADER = "// GENERATED by scripts/sync-widget-sources.py from firebase/shared/{name}. Do not edit; edit the shared file and re-run the script.\n\n"


def expected(widget: Path) -> dict[Path, str]:
    return {widget / "Sources" / f.name: HEADER.format(name=f.name) + f.read_text() for f in sorted(shared.glob("*.swift"))}


def main() -> int:
    check = "--check" in sys.argv[1:]
    problems = []
    for widget in widgets:
        want = expected(widget)
        for path, text in want.items():
            if not path.exists():
                problems.append(f"missing: {path.relative_to(root)}")
            elif path.read_text() != text:
                problems.append(f"stale:   {path.relative_to(root)}")
            if not check and (not path.exists() or path.read_text() != text):
                path.write_text(text)
        # A generated copy whose shared source was removed or renamed.
        for path in (widget / "Sources").glob("Firebase*.swift"):
            if path not in want and path.read_text().startswith("// GENERATED by scripts/sync-widget-sources.py"):
                problems.append(f"orphan:  {path.relative_to(root)}")
                if not check:
                    path.unlink()
    if check and problems:
        print("\n".join(problems))
        print("Out of sync with firebase/shared. Run: python3 firebase/scripts/sync-widget-sources.py")
        return 1
    print(f"{'in sync' if check else 'synced'}: {len(widgets)} widgets x {len(list(shared.glob('*.swift')))} shared files")
    return 0


sys.exit(main())
